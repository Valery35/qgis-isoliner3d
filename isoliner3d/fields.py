# Поля с переменной приставкой: 2.14 называет их по слою, который
# считали, `blocks_n`, `faults_len`. Подпись собирается с этой
# приставкой, чтобы три прогона по одному слою тел не слились
# в три одинаковых заголовка.
SUFFIX_LABELS = {
    "_n": "%s: объектов внутри",
    "_len": "%s: длина внутри, м",
    "_sum": "%s: сумма атрибута",
}

# Поля в метрах: координаты, отметки, длины, размеры. Округляются
# до сантиметра, потому что для координаты правило значащих цифр
# съело бы сотни метров.
METRIC = {
    "x", "y", "z", "top", "bot", "z_from", "z_to", "thick",
    "dx", "dy", "dz", "from_m", "to_m", "zmin", "zmax",
}
METRIC_SUFFIX = ("_len",)
METRIC_DECIMALS = 2

# Прочие числа: объёмы, массы, содержания, невязки. Их масштаб зависит
# от данных, содержание бывает и 25.37, и 0.0046, поэтому держится
# число значащих цифр, а целая часть не округляется никогда.
SIGNIFICANT = 4


def label_for(name):
    """Русский исходник подписи поля или None, если поле не наше."""
    if name in LABELS:
        return LABELS[name]
    for suf, text in SUFFIX_LABELS.items():
        if name.endswith(suf) and len(name) > len(suf):
            return text
    return None


def label_prefix(name):
    """Приставка поля с переменным именем: `blocks` у `blocks_n`."""
    for suf in SUFFIX_LABELS:
        if name.endswith(suf) and len(name) > len(suf) \
                and name not in LABELS:
            return name[:-len(suf)]
    return None


def all_label_sources():
    """Все русские исходники подписей, для проверки перевода."""
    return set(LABELS.values()) | set(SUFFIX_LABELS.values())


def is_metric(name):
    """Поле в метрах, округляемое до сантиметра."""
    return name in METRIC or name.endswith(METRIC_SUFFIX)


def round_significant(v, digits=SIGNIFICANT):
    """Значащие цифры, но целая часть не округляется.

    39524.123 -> 39524, 25.3745 -> 25.37, 0.0045678 -> 0.004568.
    Правило «четыре значащие» в чистом виде дало бы 39520, и объём
    потерял бы четыре кубометра на ровном месте.
    """
    if v == 0:
        return 0.0
    e = int(math.floor(math.log10(abs(v))))
    return round(v, min(max(0, digits - 1 - e), 12))


def round_value(name, v):
    """Округлить значение поля по его роду. Не число - как есть."""
    if isinstance(v, bool) or not isinstance(v, float):
        return v
    if math.isnan(v) or math.isinf(v):
        return v
    if is_metric(name):
        return round(v, METRIC_DECIMALS)
    return round_significant(v)


def split_gpkg_ref(ref):
    """(путь, имя слоя или None) для ссылки на GeoPackage, иначе None.

    Ссылка приходит двумя видами. От загрузки в проект - с именем слоя,
    `C:/путь/файл.gpkg|layername=x`. От приёмника результата - одним
    путём, и тогда имя слоя разбирает тот, кто открывает файл.
    Временный слой, shapefile и прочее сюда не попадают: подпись
    в файле умеет хранить только GeoPackage.
    """
    if not isinstance(ref, str) or not ref:
        return None
    path, sep, tail = ref.partition("|layername=")
    if not path.lower().endswith(".gpkg"):
        return None
    if not sep:
        return (path, None)
    name = tail.split("|")[0].strip()
    return (path, name or None)
