"""2.11 Булевы операции с оболочками: описание и расчёт без QGIS.

Точная операция над сетками режет треугольники друг о друга,
и на касаниях - а в геологии тела касаются постоянно - регулярно
даёт вырожденные грани и незамкнутый результат. Объём по такому
телу уже не взять, а объём здесь и есть цель.

Поэтому обе оболочки переводятся в занятость общего куба
(boolean3d.py), операция выполняется над занятостью, и результат
снова превращается в тело (voxel.py). Оно ступенчатое и точное
настолько, насколько мелка ячейка, зато замкнуто всегда.
"""

import numpy as np

from ..toolspec import N_, Param, Result, Tool, ToolError

MAX_CELLS = 60000000


def _bounds(v):
    return (float(v[:, 0].min()), float(v[:, 0].max()),
            float(v[:, 1].min()), float(v[:, 1].max()),
            float(v[:, 2].min()), float(v[:, 2].max()))


def run(values, report):
    """Расчёт 2.11 на телах values["SHELL_A"] и values["SHELL_B"]."""
    from .. import boolean3d, voxel
    from ..cleanup import mesh_volume, shell_defects, split_bodies

    op = boolean3d.OPS[int(values.get("OP") or 0)]
    cell = float(values.get("CELL") or 1.0)
    shells = []
    for key, tag in (("SHELL_A", N_("Первое тело")),
                     ("SHELL_B", N_("Второе тело"))):
        mesh = values[key]
        v = np.asarray(mesh["verts"], dtype=float)
        f = np.asarray(mesh["faces"], dtype=np.int64)
        if not len(f):
            raise ToolError(N_("%s: треугольников не нашлось. Нужен слой "
                               "полигонов с высотой, какой даёт кнопка "
                               "оболочек в окне просмотра."), tag)
        holes, _pinch = shell_defects(v, f)
        if holes:
            raise ToolError(N_("%s: оболочка не замкнута, рваных рёбер %d. "
                               "У незамкнутой внутренности нет, и "
                               "определить, что внутри, нечем."), tag, holes)
        report.info(N_("%s: граней %d, объём %.1f м3."), tag, len(f),
                    mesh_volume(v, f))
        shells.append((v, f))
    (va, fa), (vb, fb) = shells

    gt, z0, dz, shape = boolean3d.common_box(_bounds(va), _bounds(vb),
                                             cell, op)
    cells = boolean3d.cell_budget(shape)
    report.info(N_("Куб %d x %d x %d, ячеек %d."), shape[2], shape[1],
                shape[0], cells)
    if cells > MAX_CELLS:
        raise ToolError(N_("Ячеек слишком много: %d. Память растёт кубом, "
                           "укрупните ячейку."), cells)
    occ_a = boolean3d.shell_occupancy(va, fa, gt, z0, dz, shape)
    report.progress(35)
    occ_b = boolean3d.shell_occupancy(vb, fb, gt, z0, dz, shape)
    report.progress(60)
    occ = boolean3d.combine(occ_a, occ_b, op)
    n_cell = int(occ.sum())
    if not n_cell:
        raise ToolError(N_("От результата не осталось ни одной ячейки. Для "
                           "пересечения это значит, что тела не "
                           "перекрываются, для вычитания - что второе "
                           "поглотило первое."))
    report.info(N_("Занято ячеек: %d, объём по ним %.1f м3."), n_cell,
                n_cell * abs(gt[1] * gt[5]) * dz)

    # Слияние граней снимаем: оно ломает замкнутость, а объём
    # здесь и есть цель.
    verts, faces, _cls, over = voxel.voxel_mesh(
        occ, gt, z0, dz, classes=np.zeros(occ.shape, np.int32),
        merge=False)
    if over:
        raise ToolError(N_("Граней вышло слишком много: укрупните "
                           "ячейку."))
    report.progress(80)

    out = Result([("body", "int"), ("op", "string"), ("volume", "double"),
                  ("faces", "int"), ("closed", "int")],
                 name=N_("Результат (тела)"))
    total = 0.0
    n_body = 0
    for bv, bf, _tag in split_bodies(verts, faces):
        holes, _pinch = shell_defects(bv, bf)
        vol = mesh_volume(bv, bf)
        total += vol
        n_body += 1
        out.add({"verts": bv, "faces": bf},
                [n_body, op, float(vol), int(len(bf)),
                 1 if holes == 0 else 0])
    report.info(N_("Тел: %d, объём по оболочкам %.1f м3. Точность "
                   "ограничена ячейкой: ошибка идёт по площади "
                   "поверхности и убывает вместе с ячейкой."), n_body, total)
    return {"OUTPUT": out}


SPEC = Tool(
    code="2.11", name="boolean_shells",
    title=N_("Булевы операции с оболочками"), group="2",
    help=N_("Вычитает, объединяет и пересекает два тела.\n\n"
            "Так считают отработку: из оболочки рудного тела вычитают "
            "оболочку отработанной камеры и получают остаток запасов. "
            "Пересечение даёт то, что попало в зону, объединение - "
            "два тела как одно.\n\n"
            "Работа идёт не по сеткам, а по ячейкам: обе оболочки "
            "переводятся в занятость общего куба, операция выполняется "
            "над занятостью, и результат снова превращается в тело. "
            "Точная операция над сетками режет треугольники друг о "
            "друга и на касаниях регулярно даёт незамкнутый результат, "
            "по которому объём уже не взять.\n\n"
            "Цена этого решения: тело выходит ступенчатым, а точность "
            "ограничена ячейкой. Ошибка идёт по площади поверхности "
            "и убывает вместе с ячейкой: на кубе в десять метров "
            "ячейка 0.5 м дала ошибку объёма пять процентов, "
            "0.25 м - два с половиной, 0.1 м - попала точно. Память "
            "при этом растёт кубом.\n\n"
            "Оболочки на входе должны быть замкнуты: у незамкнутой "
            "внутренности нет, и определить, что внутри, нечем. "
            "Незамкнутая на входе - отказ с указанием объекта."),
    params=[
        Param("SHELL_A", "mesh", N_("Первое тело (полигоны с Z)"),
              N_("Первое тело: замкнутая оболочка из слоя полигонов с Z. "
                 "Такие даёт кнопка оболочек в окне просмотра "
                 "и инструмент 2.04.")),
        Param("SHELL_B", "mesh", N_("Второе тело (полигоны с Z)"),
              N_("Второе тело. Для вычитания это то, что вырезают "
                 "из первого: отработанная камера, зона обводнения.")),
        Param("OP", "enum", N_("Действие"),
              N_("Вычитание оставляет от первого тела то, чего нет во "
                 "втором. Объединение берёт оба, пересечение - только "
                 "общую часть."),
              default=0, options=(N_("Вычитание (первое минус второе)"),
                                  N_("Объединение"), N_("Пересечение"))),
        Param("CELL", "number", N_("Сторона ячейки, м"),
              N_("Сторона ячейки. Она и задаёт точность: ошибка идёт "
                 "по площади поверхности и убывает вместе с ячейкой вдвое "
                 "на каждую половину. На кубе в десять метров ячейка 0.5 м "
                 "дала ошибку объёма 5 процентов, 0.25 м - два с половиной, "
                 "0.1 м - попала точно. "
                 "Память растёт кубом, поэтому мельче нужного не берите."),
              default=1.0, minimum=1e-6),
        Param("OUTPUT", "sink", N_("Результат (тела)"),
              N_("Тела результата: полигоны с Z, объём каждого "
                 "в атрибутах. Оболочка замкнута всегда, поэтому объём "
                 "по ней считается."),
              geometry="polygonz"),
    ],
    run=run)
